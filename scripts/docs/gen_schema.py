#!/usr/bin/env python3
"""Generate the schema reference fragments included by docs/schema.md.

Usage:
    python scripts/docs/gen_schema.py           # (re)write the fragments
    python scripts/docs/gen_schema.py --check   # exit 1 if they are stale

The schema is built from schema/*.sql through schema/build.py's own
`build()` entry point (same file order, same version gate, same bootstrap
assert) into a throwaway DuckDB file, then introspected from the catalog:

* tables, columns and declared PRIMARY KEY / FOREIGN KEY constraints come
  from duckdb_columns() / duckdb_constraints() / duckdb_tables();
* the grouping (one diagram per DDL file) and the one-line purposes of views
  and table macros come from the DDL source text (file headers and the
  comment block directly above each CREATE), since DuckDB keeps no comments.

Relationships. DuckDB can only enforce FKs into the append-only tables
(`commit`, `axis`); FK intent into versioned tables is validated by the
`audit_dangling_ref` view instead (deviation D1). So the diagrams draw:

* solid edges  — FOREIGN KEYs declared in the DDL (engine-enforced);
* dashed edges — references implied by `*_id` column naming
  (`<table>_id`, `<role>_<table>_id`, plus the `class`/`unit` short forms),
  not enforced by the engine.

The `valid_from_commit` / `valid_to_commit` FKs that every versioned table
declares are left out of the diagrams (they would tie every box to
`commit`); the page prose states them once. Generated `cur_*` shadow columns
(one-current-row index helpers) are omitted.

Output is fully sorted/deterministic so regeneration diffs are clean.
Stdlib + duckdb only.

Public-text guard. The pages built from these fragments are public, but the
SQL comments are written for developers and cite the private design record
(specs/, plan sections, critique items, decision ids). Only two kinds of
comment text are published: each file's header title (first sentence of the
header) and each view/macro purpose (first sentence of the comment paragraph
nearest its CREATE). Those published strings are checked against
INTERNAL_REF_RE; any hit fails the run (both modes) and names the object, so
reword that comment sentence for a public reader. Comment text that is not
published may keep its internal references.
"""
