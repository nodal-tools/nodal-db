VERSIONING_COLS = {"valid_from_commit", "valid_to_commit"}
# Columns every versioned table carries; described once in the page prose
# and omitted from the diagram boxes (still listed in the column tables).
DIAGRAM_HIDDEN_COLS = VERSIONING_COLS | {"version"}
# Wider tables show only key columns in the diagram.
MAX_DIAGRAM_COLS = 14
# Files whose tables are too many/wide for one legible diagram: split by
# table-name prefix, in order (heading, prefix).
