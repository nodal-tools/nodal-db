#!/usr/bin/env python3
"""Generate the vendored name-fold table: DuckDB's `lower()` as data
(docs/dev/engine_rules.md §8).

Usage:

    python3 conformance/unicode/gen_lower_table.py UCD_15_1_DIR

The directory holds `UnicodeData.txt` of the Unicode Character Database
15.1.0 release, downloaded unchanged from
`https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt`. The file
carries no version line, so the script checks it against its pinned
SHA-256 (below) and refuses any other bytes.

Name identity in nodal-db is DuckDB's `lower()`. On the bundled engine it is
exactly Unicode 15.1.0 Simple_Lowercase_Mapping (`UnicodeData.txt` field 13),
one code point to one code point, with no context rule (no final sigma);
`crates/nodal-db-core/tests/duckdb_lower_guard.rs` proves the equality on
every scalar value. The Rust fold, `nodal_db_core::types::fold`, is that
table. The script writes:

- `conformance/unicode/lower_simple_15.1.0.txt` (next to itself): one line
  `XXXX;YYYY` per code point whose simple lowercase mapping is not itself,
  in code point order, with the source's SHA-256 in the header. The
  normative copy of the data.
- `crates/nodal-db-core/src/fold_table.rs`: the same mapping as a sorted Rust
  table (`LOWER`). The core compares the engine's `lower()` with it on every
  scalar value once per process and refuses writes if they disagree (a
  patched engine whose case table moved; `types::check_engine_fold`).
  `tests/fold_table.rs` checks the Rust table against the text file.

Regenerating is part of a DuckDB upgrade that changes `lower()`
(CONTRIBUTING.md, "DuckDB upgrades"): a new Unicode version for the fold
means new pinned hashes here. The output is deterministic; rerunning it on
the same files changes nothing.
"""
import hashlib
import pathlib
import sys

VERSION = "15.1.0"
# SHA-256 of `UnicodeData.txt` as published by unicode.org.
PINNED = {
    "15.1.0": "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86",
}
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TABLE = HERE / f"lower_simple_{VERSION}.txt"
RUST = ROOT / "crates" / "nodal-db-core" / "src" / "fold_table.rs"


def read_ucd(directory, version):
    path = pathlib.Path(directory) / "UnicodeData.txt"
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED[version]:
        sys.exit(
            f"{path}: SHA-256 {digest} is not UnicodeData.txt {version} "
            f"({PINNED[version]})"
        )
    rows = []
    for line in data.decode("utf-8").splitlines():
        f = line.split(";")
        rows.append((int(f[0], 16), f[12], f[13], f[14]))
    return rows, digest


def lower_map(rows):
    """Field 13 (Simple_Lowercase_Mapping), only where it changes the code
    point. Ranges (`<..., First>`/`<..., Last>`) carry no case mapping."""
    out = {}
    for cp, _upper, lower, _title in rows:
        if lower:
            target = int(lower, 16)
            if target != cp:
                out[cp] = target
    return out


def rust_char(cp):
    return f"'\\u{{{cp:04x}}}'"


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    rows, digest = read_ucd(argv[1], VERSION)
    table = lower_map(rows)
    for cp, target in table.items():
        assert target <= 0x10FFFF and not 0xD800 <= target <= 0xDFFF

    lines = [
        f"# Simple_Lowercase_Mapping of Unicode {VERSION} (UnicodeData.txt field 13),",
        "# only code points whose mapping is not themselves: the name fold of",
        "# nodal-db, equal to DuckDB lower() on the bundled engine",
        "# (docs/dev/engine_rules.md §8).",
        "# Generated by conformance/unicode/gen_lower_table.py; do not edit.",
        f"# Source: UnicodeData.txt {VERSION} sha256 {digest}",
        f"# Entries: {len(table)}",
        "# Format: code point;lowercase (hex)",
    ]
    lines += [f"{cp:04X};{table[cp]:04X}" for cp in sorted(table)]
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")

    rs = [
        "// Generated by conformance/unicode/gen_lower_table.py; do not edit.",
        f"// Source: UnicodeData.txt {VERSION} sha256 {digest}",
        "",
        f"//! The name fold's data: Unicode {VERSION} Simple_Lowercase_Mapping, the",
        "//! table of DuckDB's `lower()` on the bundled engine (engine_rules.md §8).",
        "//! The normative copy is `conformance/unicode/lower_simple_15.1.0.txt`;",
        "//! `tests/fold_table.rs` checks this file against it.",
        "",
        "/// Unicode version of [`LOWER`].",
        "pub const LOWER_UNICODE_VERSION: (u8, u8, u8) = (15, 1, 0);",
        "",
        "/// `(code point, simple lowercase)` for every code point the mapping",
        "/// changes, sorted by code point (binary search).",
        f"pub static LOWER: [(char, char); {len(table)}] = [",
    ]
    rs += [f"    ({rust_char(cp)}, {rust_char(table[cp])})," for cp in sorted(table)]
    rs += ["];", ""]
    RUST.write_text("\n".join(rs), encoding="utf-8")
    print(f"{TABLE.relative_to(ROOT)}: {len(table)} entries")
    print(f"{RUST.relative_to(ROOT)}: LOWER {len(table)}")


if __name__ == "__main__":
    main(sys.argv)
