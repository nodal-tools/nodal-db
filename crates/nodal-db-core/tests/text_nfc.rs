/// The normalization tables are Unicode 16.0.0, the version spec §3.4.1.1
/// pins (plan §4, P2). `unicode-normalization = "=0.1.24"` is what gives
/// 16.0.0 (0.1.23 is 15.1.0, 0.1.25 is 17.0.0): a crate bump in either
/// direction changes NFC for characters assigned in between, which is a
/// rehash-class change (spec §2.4), so it must fail here first.
#[test]
fn normalization_tables_are_unicode_16_0_0() {
    assert_eq!(nodal_db_core::text::UNICODE_VERSION, (16, 0, 0));
    assert_eq!(unicode_normalization::UNICODE_VERSION, (16, 0, 0));
    // The plan §1.4 strings whose NFC differs between 15.x, 16.0 and 17.0:
    // new 16.0 composites, and a 17.0 reorder that 16.0 does not do.
    assert_eq!(nfc("\u{11382}\u{113c9}"), "\u{11383}");
    assert_eq!(nfc("\u{105d2}\u{307}"), "\u{105c9}");
    assert_eq!(nfc("a\u{1acf}\u{323}"), "a\u{1acf}\u{323}");
}

// ---------------------------------------------------------------------------
// The vendored Unicode 16.0.0 data (plan §4, P3): the crate against the
// table for every scalar value, and the core's `nfc` against the official
// NormalizationTest. Three-way: the crate (built from its own copy of the
// UCD), the table (generated by `conformance/unicode/gen_nfc_table.py`) and
// NormalizationTest (Unicode's own), so a generator bug cannot hide.
// ---------------------------------------------------------------------------

use std::collections::{HashMap, HashSet};
use std::io::Read;
use std::path::PathBuf;

use unicode_normalization::char::{canonical_combining_class, compose, decompose_canonical};

fn unicode_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../conformance/unicode")
}

/// One table line: combining class, one-level canonical decomposition,
/// Full_Composition_Exclusion.
struct Entry {
    ccc: u8,
    decomposition: Vec<char>,
    excluded: bool,
}

fn hex_char(s: &str) -> char {
    char::from_u32(u32::from_str_radix(s, 16).expect("hex code point")).expect("scalar value")
}

fn load_table() -> HashMap<char, Entry> {
    let text = std::fs::read_to_string(unicode_dir().join("nfc_table_16.0.0.txt"))
        .expect("read conformance/unicode/nfc_table_16.0.0.txt");
    let mut table = HashMap::new();
    for line in text
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
    {
        let f: Vec<&str> = line.split(';').collect();
        assert_eq!(f.len(), 4, "table line {line:?}");
        let entry = Entry {
            ccc: f[1].parse().expect("ccc"),
            decomposition: f[2].split_whitespace().map(hex_char).collect(),
            excluded: f[3] == "1",
        };
        table.insert(hex_char(f[0]), entry);
    }
    assert!(table.len() > 3000, "table has {} entries", table.len());
    table
}

const S_BASE: u32 = 0xAC00;
const S_COUNT: u32 = 11_172;

fn is_hangul_syllable(c: char) -> bool {
    (S_BASE..S_BASE + S_COUNT).contains(&(c as u32))
}

/// The algorithmic Hangul decomposition (Unicode §3.12), one level:
/// LV -> L V, LVT -> LV T.
fn hangul_one_level(c: char) -> Vec<char> {
    let s = c as u32;
    let si = s - S_BASE;
    let t = si % 28;
    let ch = |cp: u32| char::from_u32(cp).unwrap();
    if t == 0 {
        vec![
            ch(0x1100 + si / (21 * 28)),
            ch(0x1161 + (si % (21 * 28)) / 28),
        ]
    } else {
        vec![ch(s - t), ch(0x11A7 + t)]
    }
}

fn full_decomposition(table: &HashMap<char, Entry>, c: char, out: &mut Vec<char>) {
    if is_hangul_syllable(c) {
        for d in hangul_one_level(c) {
            full_decomposition(table, d, out);
        }
        return;
    }
    match table.get(&c) {
        Some(e) if !e.decomposition.is_empty() => {
            for &d in &e.decomposition {
                full_decomposition(table, d, out);
            }
        }
        _ => out.push(c),
    }
}

/// The pinned crate agrees with the vendored Unicode 16.0.0 table on every
/// scalar value: canonical combining class, full canonical decomposition,
/// and pair recomposition (a primary composite recomposes, an excluded code
/// point never does; Hangul algorithmically).
#[test]
fn crate_matches_the_vendored_table_for_every_scalar_value() {
    let table = load_table();
    let mut mismatches: Vec<String> = Vec::new();
    let mut by_crate = Vec::new();
    let mut by_table = Vec::new();
    for c in (0..=0x10_FFFFu32).filter_map(char::from_u32) {
        let entry = table.get(&c);
        let ccc = entry.map_or(0, |e| e.ccc);
        if canonical_combining_class(c) != ccc {
            mismatches.push(format!(
                "U+{:04X}: ccc crate {} table {ccc}",
                c as u32,
                canonical_combining_class(c)
            ));
        }
        by_crate.clear();
        decompose_canonical(c, |d| by_crate.push(d));
        by_table.clear();
        full_decomposition(&table, c, &mut by_table);
        if by_crate != by_table {
            mismatches.push(format!(
                "U+{:04X}: decomposition crate {by_crate:?} table {by_table:?}",
                c as u32
            ));
        }
        let pair = if is_hangul_syllable(c) {
            Some((hangul_one_level(c), false))
        } else {
            entry
                .filter(|e| e.decomposition.len() == 2)
                .map(|e| (e.decomposition.clone(), e.excluded))
        };
        if let Some((d, excluded)) = pair {
            let composed = compose(d[0], d[1]);
            if (excluded && composed == Some(c)) || (!excluded && composed != Some(c)) {
                mismatches.push(format!(
                    "U+{:04X}: compose({d:?}) = {composed:?}, excluded = {excluded}",
                    c as u32
                ));
            }
        }
    }
    assert!(
        mismatches.is_empty(),
        "unicode-normalization disagrees with conformance/unicode/nfc_table_16.0.0.txt \
         ({} mismatches):\n{}",
        mismatches.len(),
        mismatches[..mismatches.len().min(30)].join("\n")
    );
}

fn parse_column(field: &str) -> String {
    field.split_whitespace().map(hex_char).collect()
}

/// The core's `text::nfc` (and `text::is_nfc`) pass the official
/// NormalizationTest-16.0.0: c2 == NFC(c1) == NFC(c2) == NFC(c3) and
/// c4 == NFC(c4) == NFC(c5) on every line, and every code point Part 1
/// does not list is unchanged.
#[test]
fn core_nfc_passes_normalization_test_16() {
    let mut gz = flate2::read::GzDecoder::new(
        std::fs::File::open(unicode_dir().join("NormalizationTest-16.0.0.txt.gz"))
            .expect("open NormalizationTest-16.0.0.txt.gz"),
    );
    let mut text = String::new();
    gz.read_to_string(&mut text)
        .expect("gunzip NormalizationTest");
    assert!(
        text.starts_with("# NormalizationTest-16.0.0.txt"),
        "not the 16.0.0 NormalizationTest"
    );
    let mut part = "";
    let mut part1: HashSet<char> = HashSet::new();
    let mut failures: Vec<String> = Vec::new();
    let mut lines = 0;
    for raw in text.lines() {
        let line = raw.split('#').next().unwrap().trim();
        if line.is_empty() {
            continue;
        }
        if line.starts_with('@') {
            part = line;
            continue;
        }
        let cols: Vec<String> = line.split(';').take(5).map(parse_column).collect();
        lines += 1;
        if part == "@Part1" {
            part1.insert(cols[0].chars().next().unwrap());
        }
        for (i, want) in [(0, 1), (1, 1), (2, 1), (3, 3), (4, 3)] {
            let (input, want) = (&cols[i], &cols[want]);
            let got = nfc(input);
            if got != *want {
                failures.push(format!("{part} {line}: NFC(c{}) = {got:?}", i + 1));
            }
            if is_nfc(input) != (input == want) {
                failures.push(format!("{part} {line}: is_nfc(c{})", i + 1));
            }
        }
    }
    assert!(lines > 19_000 && !part1.is_empty(), "{lines} test lines");
    let mut buf = [0u8; 4];
    for c in (0..=0x10_FFFFu32).filter_map(char::from_u32) {
        if part1.contains(&c) {
            continue;
        }
        let s: &str = c.encode_utf8(&mut buf);
        if !matches!(nfc(s), Cow::Borrowed(_)) || !is_nfc(s) {
            failures.push(format!(
                "Part 1: U+{:04X} is not listed but changes",
                c as u32
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "text::nfc fails NormalizationTest-16.0.0 ({} failures):\n{}",
        failures.len(),
        failures[..failures.len().min(30)].join("\n")
    );
}
